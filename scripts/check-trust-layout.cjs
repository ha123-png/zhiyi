const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
(async()=>{
  const out=process.env.ZHIYI_VISUAL_OUT || '.local/tests/trust-visual'; fs.mkdirSync(out,{recursive:true});
  const url=process.env.ZHIYI_ACCEPTANCE_URL || 'http://127.0.0.1:8813';
  const browser=await chromium.launch({...(process.env.ZHIYI_BROWSER_CHANNEL ? {channel:process.env.ZHIYI_BROWSER_CHANNEL} : {}),headless:true});
  const page=await browser.newPage({viewport:{width:1366,height:900}});
  await page.context().tracing.start({screenshots:true,snapshots:true});
  const report={scenarios:[],passed:false};
  async function screenshot(name) {
    await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(a=>a.effect?.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));});
    await page.screenshot({path:path.join(out,name)});
  }
  try {
    const body={name:'版本与拖动验收',fields:Array.from({length:14},(_,i)=>({key:`field_${i}`,label:`验收字段 ${i+1}`,value_type:'text',section:i%2?'item':'header'})),extra_instructions:'保留旧版要求'};
    const create=await page.request.post(url+'/api/v1/templates',{data:body}); assert.equal(create.status(),201);
    const template=await create.json();
    const changed=await page.request.put(`${url}/api/v1/templates/${template.id}`,{data:{...body,fields:[...body.fields].reverse(),extra_instructions:'新的提取要求',expected_version:1}}); assert.equal(changed.status(),200);
    await page.goto(url);
    if(await page.getByRole('button',{name:'跳过引导'}).isVisible()) await page.getByRole('button',{name:'跳过引导'}).click();
    await page.getByRole('button',{name:'模板',exact:true}).click();
    await page.locator('.tpl-item-name').getByText(body.name,{exact:true}).click();
    await page.getByRole('button',{name:'第 2 版 · 查看历史',exact:true}).click();
    const dialog=page.getByRole('dialog',{name:'模板历史'});
    await dialog.getByRole('button',{name:/第 1 版/}).click();
    await dialog.getByText('阅读顺序',{exact:true}).waitFor();
    assert(await dialog.getByText('保留旧版要求',{exact:true}).isVisible());
    await screenshot('template-history-light.png');
    await page.evaluate(()=>document.documentElement.classList.add('dark'));
    await screenshot('template-history-dark.png');
    await page.setViewportSize({width:480,height:760});
    await screenshot('template-history-narrow.png');
    assert.equal(await dialog.evaluate(e=>e.scrollWidth>e.clientWidth),false,'History fits narrow viewport');
    const restoreBounds=await dialog.getByRole('button',{name:'设为当前版本'}).boundingBox();
    assert(restoreBounds && restoreBounds.y+restoreBounds.height<=760,'Restore stays reachable in narrow dialog');
    await page.setViewportSize({width:1366,height:900});
    await page.evaluate(()=>document.documentElement.classList.remove('dark'));
    const restorePattern=`**/templates/${template.id}/versions/1/restore`;
    await page.route(restorePattern,route=>route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({detail:'验收冲突：其他窗口已更新模板。'})}));
    await dialog.getByRole('button',{name:'设为当前版本'}).click();
    await dialog.getByRole('alert').getByText('验收冲突：其他窗口已更新模板。').waitFor();
    assert(await dialog.isVisible());
    await page.unroute(restorePattern);
    await dialog.getByRole('button',{name:'设为当前版本'}).click();
    await page.getByRole('button',{name:'第 1 版 · 查看历史',exact:true}).waitFor();
    const restored=await (await page.request.get(`${url}/api/v1/templates/${template.id}`)).json();
    assert.deepEqual(restored.fields.map(f=>f.key),body.fields.map(f=>f.key));
    assert.equal(restored.version,1);
    assert.equal((await (await page.request.get(`${url}/api/v1/templates/${template.id}/versions`)).json()).length,2);
    await page.getByRole('button',{name:'第 1 版 · 查看历史',exact:true}).click();
    await dialog.getByText('最近恢复记录',{exact:true}).click();
    await dialog.getByText('从第 2 版恢复到第 1 版',{exact:false}).waitFor();
    await screenshot('template-restoration-record.png');
    await dialog.getByRole('button',{name:'关闭模板历史'}).click();
    report.scenarios.push('history-diff-conflict-switch-current-version');
    const input=page.getByRole('textbox',{name:'字段名',exact:true}).first();
    await input.fill('未保存的字段');
    await page.getByRole('button',{name:'第 1 版 · 查看历史',exact:true}).click();
    await dialog.getByRole('button',{name:/第 2 版/}).click();
    assert(await dialog.getByRole('button',{name:'设为当前版本'}).isDisabled());
    await dialog.getByRole('button',{name:'关闭模板历史'}).click(); await input.fill(body.fields[0].label);
    report.scenarios.push('history-protects-unsaved-draft');
    const order=()=>page.getByRole('textbox',{name:'字段名',exact:true}).evaluateAll(nodes=>nodes.map(n=>n.value));
    const original=await order();
    const handle=page.getByRole('button',{name:`移动字段 ${original[0]}`,exact:true});
    await handle.scrollIntoViewIfNeeded(); await handle.hover();
    const from=await handle.boundingBox(); const target=await page.locator('.template-field').nth(2).boundingBox();
    await page.mouse.move(from.x+from.width/2,from.y+from.height/2); await page.mouse.down();
    await page.mouse.move(from.x+from.width/2,target.y+target.height*.8,{steps:10});
    assert.equal(await page.locator('.field-lifted').count(),1);
    assert.equal(await page.locator('.field-sort-placeholder').count(),1);
    assert.notEqual(await page.locator('.template-field').nth(1).evaluate(e=>getComputedStyle(e).transform),'none');
    await screenshot('field-lift-and-displacement.png');
    await page.keyboard.press('Escape'); await page.mouse.up(); assert.deepEqual(await order(),original);
    await handle.dragTo(page.locator('.template-field').nth(2),{targetPosition:{x:40,y:35}});
    await page.waitForFunction(label=>document.querySelectorAll('.field-name-control input')[2]?.value===label,original[0]);
    assert(await handle.evaluate(e=>e===document.activeElement));
    await page.keyboard.press('ArrowUp');
    assert.equal((await order())[1],original[0]);
    report.scenarios.push('lift-displace-drop-escape-keyboard-focus');
    // Hold near the lower edge: scrolling must continue without more pointer events.
    await handle.hover(); const start=await handle.boundingBox();
    await page.mouse.move(start.x+start.width/2,start.y+start.height/2); await page.mouse.down();
    await page.mouse.move(start.x+start.width/2,895,{steps:8});
    const scrollBefore=await page.locator('.app-page-wrap').evaluate(e=>e.scrollTop);
    await page.waitForTimeout(350);
    assert((await page.locator('.app-page-wrap').evaluate(e=>e.scrollTop))>scrollBefore,'Edge scroll continues while held');
    await page.keyboard.press('Escape'); await page.mouse.up();
    report.scenarios.push('continuous-edge-scroll');
    await page.getByRole('button',{name:'高级设置',exact:true}).click();
    await page.getByLabel('规则类型').selectOption('pattern');
    await page.getByLabel('格式表达式（正则）').fill('PO-\\d{3}');
    await page.getByLabel('试填一个值').fill('PO-001');
    await page.getByRole('button',{name:'检查格式',exact:true}).click();
    await page.getByText('整段匹配通过。',{exact:true}).waitFor();
    await screenshot('rule-preview-light.png');
    await page.getByLabel('试填一个值').fill('编号 PO-001');
    assert.equal(await page.getByText('整段匹配通过。',{exact:true}).count(),0);
    await page.getByRole('button',{name:'检查格式',exact:true}).click();
    await page.getByText('整段匹配不通过。',{exact:true}).waitFor();
    await page.setViewportSize({width:480,height:760});
    await page.getByLabel('试填一个值').scrollIntoViewIfNeeded();
    await screenshot('rule-preview-narrow.png');
    assert.equal(await page.locator('.deterministic-rules-editor').evaluate(e=>e.scrollWidth>e.clientWidth),false);
    await page.setViewportSize({width:1366,height:900});
    report.scenarios.push('server-rule-preview-fullmatch-narrow');
    await page.getByRole('button',{name:'设置',exact:true}).click();
    const headingStyle = await page.locator('.page-header h1').evaluate(e=>({size:getComputedStyle(e).fontSize,font:getComputedStyle(e).fontFamily}));
    await page.getByRole('button',{name:'使用说明',exact:false}).click();
    await page.getByRole('heading',{name:'使用说明',exact:true}).waitFor();
    await page.locator('.app-page-wrap').evaluate(e=>e.scrollTop=0);
    assert.deepEqual(await page.locator('.page-header h1').evaluate(e=>({size:getComputedStyle(e).fontSize,font:getComputedStyle(e).fontFamily})),headingStyle,'Guide shares the app heading style');
    assert.equal(await page.locator('.guide-page .card').count(),4);
    assert(await page.locator('.guide-page .card').evaluateAll(nodes=>nodes.every(e=>parseFloat(getComputedStyle(e).borderTopWidth)>0)),'Guide uses bordered cards');
    await screenshot('guide-light.png');
    await page.getByRole('button',{name:'模板怎么越用越顺手？',exact:true}).click();
    await screenshot('guide-expanded.png');
    assert.equal(await page.locator('.guide-start').evaluate(e=>e.scrollWidth>e.clientWidth),false);
    await page.evaluate(()=>localStorage.setItem('theme','dark')); await page.reload();
    await page.getByRole('button',{name:'使用说明',exact:false}).click();
    await screenshot('guide-dark.png');
    await page.setViewportSize({width:480,height:760});
    await page.getByRole('button',{name:'模板怎么越用越顺手？',exact:true}).click();
    await screenshot('guide-narrow-expanded.png');
    await page.locator('.app-page-wrap').evaluate(e=>e.scrollTop=0);
    await screenshot('guide-narrow.png');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.emulateMedia({reducedMotion:'reduce'});
    assert.equal(await page.locator('.app-page-wrap').evaluate(e=>getComputedStyle(e).animationName),'none');
    report.scenarios.push('guide-light-dark-narrow-reduced-motion');
    report.passed=true;
  } finally {
    if(!report.passed) await page.screenshot({path:path.join(out,'trust-failure.png')}).catch(()=>{});
    fs.writeFileSync(path.join(out,'trust-report.json'),JSON.stringify(report,null,2));
    await page.context().tracing.stop({path:path.join(out,'trust-trace.zip')}); await browser.close();
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
